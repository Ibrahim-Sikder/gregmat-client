"use client";

import React from "react";
import { useAppSelector } from "@/redux/hooks";

// Define the shape of the feedback structure
interface FeedbackPoint {
  point: string;
  description: string;
}

interface SectionFeedback {
  introduction: string[];
  bodyParagraph1: string[];
  bodyParagraph2: string[];
  conclusion: string[];
}

interface DetailedFeedback {
  score: number;
  wordCount: number;
  goodPoints: FeedbackPoint[];
  areasForImprovement: FeedbackPoint[];
  sectionFeedback: SectionFeedback;
  summaryAndRecommendations: string;
  suggestedScore: string;
  estimatedTime?: string;
  // Legacy fields fallback
  summary?: string;
  overallAdvice?: string;
  development?: string;
  organization?: string;
  grammar?: string;
  bodyParagraph1?: string;
  bodyParagraph2?: string;
  conclusion?: string;
}

export default function Feedback() {
  const { essay } = useAppSelector((state) => state.writingEssay);
  const feedback = essay?.feedback as DetailedFeedback | undefined;

  if (!feedback) {
    return (
      <div className="text-center py-12 text-gray-500">
        No feedback available yet.
      </div>
    );
  }

  // Helper to safely render sections if they exist
  const hasDetailedStructure =
    feedback.goodPoints &&
    Array.isArray(feedback.goodPoints) &&
    feedback.sectionFeedback;

  if (!hasDetailedStructure) {
    return <LegacyFeedback feedback={feedback} />;
  }

  return (
    <div className="space-y-8 text-gray-800 font-sans">
      {/* Disclaimer Box */}
      <div className="bg-blue-50 p-4 rounded-md text-sm text-gray-700 leading-relaxed border border-blue-100">
        Please note that the feedback is generated by an AI model and may not be
        accurate. We recommend trying the options in{" "}
        <a
          href="https://help.gregmat.com/en/article/how-can-i-get-my-essays-reviewed-1a7rep6/"
          target="_blank"
          rel="noopener noreferrer"
          className="text-blue-600 underline  hover:text-blue-800"
        >
          this article
        </a>{" "}
        for more accurate feedback.
      </div>

      {/* Header Info */}
      <div className="space-y-4">
        <h2 className="text-xl font-bold text-slate-800">
          GRE Essay Evaluation
        </h2>

        <div className="space-y-2 text-base">
          <div>
            <span className="font-bold text-gray-700">Score: </span>
            <span>{feedback.score}</span>
          </div>
          <div>
            <span className="font-bold text-gray-700">Word count: </span>
            <span>{feedback.wordCount}</span>
          </div>
        </div>
      </div>

      {/* Good Points */}
      <div className="space-y-4">
        <h3 className="text-lg font-bold text-slate-700">Three Good Points</h3>
        <div className="space-y-4 pl-1">
          {feedback.goodPoints.map((item, idx) => (
            <div
              key={idx}
              className="flex gap-3 text-sm leading-relaxed text-gray-700"
            >
              <span className="font-medium text-gray-900 min-w-[12px]">
                {idx + 1}.
              </span>
              <span>
                <strong className="text-gray-900">{item.point}:</strong>{" "}
                {item.description}
              </span>
            </div>
          ))}
        </div>
      </div>

      {/* Areas for Improvement */}
      <div className="space-y-4">
        <h3 className="text-lg font-bold text-slate-700">
          Three Areas for Improvement
        </h3>
        <div className="space-y-4 pl-1">
          {feedback.areasForImprovement.map((item, idx) => (
            <div
              key={idx}
              className="flex gap-3 text-sm leading-relaxed text-gray-700"
            >
              <span className="font-medium text-gray-900 min-w-[12px]">
                {idx + 1}.
              </span>
              <span>
                <strong className="text-gray-900">{item.point}:</strong>{" "}
                {item.description}
              </span>
            </div>
          ))}
        </div>
      </div>

      {/* Section-by-Section Feedback */}
      <div className="space-y-6 pt-4 border-t border-gray-100">
        <h3 className="text-lg font-bold text-slate-700">
          Section-by-Section Feedback
        </h3>

        <SectionBlock
          title="Introduction"
          items={feedback.sectionFeedback.introduction}
        />
        <SectionBlock
          title="First Body Paragraph"
          items={feedback.sectionFeedback.bodyParagraph1}
        />
        <SectionBlock
          title="Second Body Paragraph"
          items={feedback.sectionFeedback.bodyParagraph2}
        />
        <SectionBlock
          title="Conclusion"
          items={feedback.sectionFeedback.conclusion}
        />
      </div>

      {/* Summary */}
      <div className="space-y-4 pt-4 border-t border-gray-100">
        <h3 className="text-lg font-bold text-slate-700">
          Summary and Final Recommendations
        </h3>
        <p className="text-sm text-gray-700 leading-relaxed">
          {feedback.summaryAndRecommendations}
        </p>
        <div className="text-sm">
          <span className="font-bold text-gray-900">Suggested score: </span>
          <span className="text-gray-700">{feedback.suggestedScore}</span>
        </div>
      </div>
    </div>
  );
}

function SectionBlock({ title, items }: { title: string; items: string[] }) {
  if (!items || items.length === 0) return null;
  return (
    <div className="space-y-2">
      <h4 className="font-semibold text-gray-800 text-base underline decoration-gray-300 underline-offset-4 decoration-1">
        {title}:
      </h4>
      <ul className="list-disc pl-5 space-y-1.5">
        {items.map((point, idx) => (
          <li key={idx} className="text-sm text-gray-700 leading-relaxed pl-1">
            {point}
          </li>
        ))}
      </ul>
    </div>
  );
}

// Legacy fallback
function LegacyFeedback({ feedback }: { feedback: any }) {
  return (
    <div className="space-y-6 text-gray-800">
      <div className="bg-blue-50 p-4 rounded-md text-sm text-gray-700 border border-blue-100">
        AI Evaluation (Legacy Format)
      </div>

      <div>
        <span className="font-bold">Score: </span> {feedback.score}
      </div>

      {feedback.summary && (
        <div>
          <h3 className="font-bold mb-1">Summary</h3>
          <p className="text-sm">{feedback.summary}</p>
        </div>
      )}

      <div className="grid gap-4">
        {feedback.bodyParagraph1 && (
          <div>
            <h4 className="font-semibold underline">Body Paragraph 1</h4>
            <p className="text-sm mt-1">{feedback.bodyParagraph1}</p>
          </div>
        )}
        {feedback.bodyParagraph2 && (
          <div>
            <h4 className="font-semibold underline">Body Paragraph 2</h4>
            <p className="text-sm mt-1">{feedback.bodyParagraph2}</p>
          </div>
        )}
        {feedback.conclusion && (
          <div>
            <h4 className="font-semibold underline">Conclusion</h4>
            <p className="text-sm mt-1">{feedback.conclusion}</p>
          </div>
        )}
      </div>
    </div>
  );
}
